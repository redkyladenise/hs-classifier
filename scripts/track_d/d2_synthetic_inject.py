import os
import sys
import numpy as np
import pandas as pd
from pathlib import Path
import duckdb

def main():
    print("=" * 60)
    print("Track D - Step D2.2: Synthetic Noise Injection & Handling")
    print("=" * 60)

    # Set reproducibility seed
    np.random.seed(42)

    out_dir = Path("data/audit/synthetic")
    out_dir.mkdir(parents=True, exist_ok=True)

    con = duckdb.connect()

    # 1. Load the synthetic base (clean)
    base_df = con.execute("SELECT group_l1, ahtn8, ch2, hd4 FROM 'data/audit/synthetic_base.parquet'").df()
    
    # 2. Get all eligible 8-digit codes from the training pool to use as "wrong" codes
    valid_codes_df = con.execute("""
        SELECT DISTINCT 
            ahtn8, 
            SUBSTRING(ahtn8, 1, 2) AS ch2, 
            SUBSTRING(ahtn8, 1, 4) AS hd4,
            SUBSTRING(ahtn8, 1, 6) AS sh6
        FROM 'data/processed/train_pairs_main.parquet'
    """).df()

    # Create a clean version of the base with required columns
    clean_df = base_df.copy()
    clean_df['sh6'] = clean_df['ahtn8'].str[:6]
    clean_df['weight'] = 1.0

    # Save the clean baseline (no noise)
    clean_df.to_parquet(out_dir / "syn_clean.parquet", index=False)
    print(f"Saved syn_clean.parquet with {len(clean_df)} pairs.")

    noise_levels = [0.10, 0.20]
    
    for noise in noise_levels:
        print(f"\n--- Processing {int(noise*100)}% Noise Level ---")
        
        # Sample descriptions to inject noise into
        n_inject = int(len(clean_df) * noise)
        injected_groups = clean_df.sample(n=n_inject, random_state=int(noise*100))['group_l1'].tolist()
        
        noisy_records = []

        for row in clean_df.itertuples(index=False):
            # True pair
            noisy_records.append({
                'group_l1': row.group_l1, 'ahtn8': row.ahtn8, 'ch2': row.ch2, 
                'hd4': row.hd4, 'sh6': row.sh6, 'weight': 1.0, 'is_injected': False
            })

            # If chosen for noise, add a wrong pair
            if row.group_l1 in injected_groups:
                # Find valid codes in the same chapter but different heading
                candidates = valid_codes_df[
                    (valid_codes_df['ch2'] == row.ch2) & 
                    (valid_codes_df['hd4'] != row.hd4)
                ]
                
                if not candidates.empty:
                    # Fix: Use a valid 32-bit random integer generated by np.random
                    seed_val = np.random.randint(0, 2**31 - 1)
                    wrong_row = candidates.sample(n=1, random_state=seed_val).iloc[0]
                    
                    # Draw wrong code share r from uniform [0.1, 0.7]
                    r = np.round(np.random.uniform(0.1, 0.7), 4)
                    
                    # Update true pair's weight
                    noisy_records[-1]['weight'] = round(1.0 - r, 4)
                    noisy_records[-1]['is_injected'] = True
                    
                    # Add wrong pair
                    noisy_records.append({
                        'group_l1': row.group_l1, 'ahtn8': wrong_row['ahtn8'], 
                        'ch2': wrong_row['ch2'], 'hd4': wrong_row['hd4'], 
                        'sh6': wrong_row['sh6'], 'weight': r, 'is_injected': True
                    })

        noisy_df = pd.DataFrame(noisy_records)
        
        # Save Noisy Variant
        out_noisy = noisy_df.drop(columns=['is_injected'])
        out_noisy.to_parquet(out_dir / f"syn_noisy_{int(noise*100)}.parquet", index=False)
        print(f"Saved noisy_{int(noise*100)}: {len(out_noisy)} pairs (injected {n_inject} conflicts).")

        # --- Apply H1 (Majority Label) ---
        h1_df = noisy_df.sort_values(by=['group_l1', 'weight', 'ahtn8'], ascending=[True, False, True])
        h1_df = h1_df.drop_duplicates(subset=['group_l1'], keep='first').copy()
        h1_df['weight'] = 1.0
        h1_out = h1_df.drop(columns=['is_injected'])
        h1_out.to_parquet(out_dir / f"syn_h1_{int(noise*100)}.parquet", index=False)
        print(f"Saved H1_{int(noise*100)}      : {len(h1_out)} pairs (1 per description).")

        # --- Apply H2 (Drop Conflicted) ---
        h2_df = noisy_df[~noisy_df['is_injected']].copy()
        h2_out = h2_df.drop(columns=['is_injected'])
        h2_out.to_parquet(out_dir / f"syn_h2_{int(noise*100)}.parquet", index=False)
        print(f"Saved H2_{int(noise*100)}      : {len(h2_out)} pairs (dropped all {n_inject} conflicted groups).")

        # --- Apply H3 (Down-weight by 0.5) ---
        h3_df = noisy_df.copy()
        h3_df.loc[h3_df['is_injected'], 'weight'] = h3_df.loc[h3_df['is_injected'], 'weight'] * 0.5
        h3_out = h3_df.drop(columns=['is_injected'])
        h3_out.to_parquet(out_dir / f"syn_h3_{int(noise*100)}.parquet", index=False)
        print(f"Saved H3_{int(noise*100)}      : {len(h3_out)} pairs (retained all, halved conflict weights).")

    print("\nAll synthetic variants built successfully.")

if __name__ == "__main__":
    main()